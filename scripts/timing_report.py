#!/usr/bin/env python3
"""Summarize results/timing/*.json (written by scripts/timed.py) for the paper and README.

Usage: python3 scripts/timing_report.py      (or `make timing`)
Writes:
  results/timing/summary.md   one table per run and the per-check times of the Halmos suites
  results/timing/caption.tex  the sentence for the paper's Halmos table, ready to \\input
Every number is read from the JSON files; nothing is hard-coded. Timing differs between runs and
machines, so these files are git-ignored and not part of `make reproduce`.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DIR = ROOT / "results" / "timing"

SUITES = [("halmos_token", "token", "checks"),
          ("halmos_bridged", "bridged token", "checks"),
          ("halmos_tiered", "tiered authority", "checks")]


def dur(s: float) -> str:
    """12.8 -> '12.8 s'; 153.7 -> '154 s'; 1800 -> '30.0 min'; 7200 -> '2.0 h'."""
    if s < 100:
        return f"{s:.1f} s"
    if s < 600:
        return f"{s:.0f} s"
    if s < 5400:
        return f"{s / 60:.1f} min"
    return f"{s / 3600:.1f} h"


def tex(s: str) -> str:
    """Thin space between a number and its unit, as in the paper."""
    return re.sub(r"(\d) (s|min|h)\b", r"\1\\,\2", s)


def main() -> int:
    runs = {}
    for f in sorted(DIR.glob("*.json")):
        try:
            r = json.loads(f.read_text())
        except json.JSONDecodeError:
            continue
        if isinstance(r, dict) and "label" in r and "wall_s" in r:
            runs[r["label"]] = r
    runs = dict(sorted(runs.items(), key=lambda kv: kv[1].get("started_utc", "")))  # in the order they ran
    if not runs:
        print(f"no timing records in {DIR.relative_to(ROOT)}; run `make prove` or `make mutate` first")
        return 1

    md = ["# Timing", "",
          "Generated by `scripts/timing_report.py` from `results/timing/*.json` (`make timing`).",
          "Timing depends on the machine and varies between runs; it is not part of `make reproduce`.", "",
          "| Run | Exit | Wall | CPU | Cores available | Cores used (avg.) | Solver threads | Halmos | Commit |",
          "|---|---:|---:|---:|---:|---:|---:|---|---|"]
    for label, r in runs.items():
        md.append(f"| `{label}` | {r['exit_code']} | {dur(r['wall_s'])} | {dur(r['cpu_s'])} | "
                  f"{r['cores_available']} | {r['cores_used_avg']} | {r.get('solver_threads') or '—'} | "
                  f"{r.get('halmos') or '—'} | {r.get('git_commit') or '—'} |")
    machines = {(r["cpu_model"], r["os"], r["logical_cpus_on_machine"], r.get("ci")) for r in runs.values()}
    md += ["", "Machine(s): " + "; ".join(
        f"{cpu}, {cpus} logical CPUs, {os_}{' (CI)' if ci else ''}" for cpu, os_, cpus, ci in sorted(machines)), ""]

    for label, r in runs.items():
        if not r.get("checks"):
            continue
        md += [f"## `{label}`", "", "| Check | Result | Paths | Time |", "|---|---|---:|---:|"]
        for c in sorted(r["checks"], key=lambda c: -c["time_s"]):
            paths = f"{c['paths']:,}" if c.get("paths") is not None else "—"
            md.append(f"| `{c['check']}` | {c['result']} | {paths} | {c['time_s']:.2f} s |")
        if r.get("suite"):
            s = r["suite"]
            md.append(f"\nHalmos total: {s['passed']} passed, {s['failed']} failed, {dur(s['time_s'])}.")
        md.append("")

    # ---- the sentence for the paper (Halmos table caption)
    parts, ref = [], None
    for label, name, unit in SUITES:
        r = runs.get(label)
        if r is None:
            continue
        ref = ref or r
        n = r["suite"]["passed"] + r["suite"]["failed"] if r.get("suite") else len(r["checks"])
        parts.append(f"{name} {n} {unit} in {dur(r['wall_s'])}")
    if parts:
        proof_runs = [runs[l] for l, _, _ in SUITES if l in runs]
        threads = sorted({r.get("solver_threads") for r in proof_runs if r.get("solver_threads")})
        avail = sorted({r["cores_available"] for r in proof_runs})
        used = sum(r["cpu_s"] for r in proof_runs) / sum(r["wall_s"] for r in proof_runs)
        cfg = (f"{', '.join(map(str, avail))} core{'s' if avail != [1] else ''} available, "
               f"{used:.1f} in use on average"
               + (f", \\texttt{{--solver-threads {', '.join(map(str, threads))}}}" if threads else "")
               + (f", Halmos {ref['halmos'].split()[-1]}" if ref.get("halmos") else ""))
        sentence = "All pass; wall-clock times: " + ", ".join(parts) + f" ({cfg})."
        (DIR / "caption.tex").write_text(
            "% Generated by scripts/timing_report.py from results/timing/*.json; do not edit by hand.\n"
            f"% CPU: {ref['cpu_model']}; commit {ref.get('git_commit')}\n" + tex(sentence) + "\n")
        md += ["## Sentence for the paper", "",
               "Written to `results/timing/caption.tex` for `\\input` into the Halmos table's caption:", "",
               "> " + sentence.replace("\\texttt{", "`").replace("}", "`"), ""]

    (DIR / "summary.md").write_text("\n".join(md) + "\n")
    print("written to", (DIR / "summary.md").relative_to(ROOT),
          "and caption.tex" if parts else "(no Halmos suites, so no caption.tex)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
