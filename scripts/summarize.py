#!/usr/bin/env python3
"""Summarize the measured gas in results/*.csv as the tables and derived figures of the paper.

Usage: python3 scripts/summarize.py [output.md]      (default: results/summary.md)
Every number is read or computed from the CSVs written by `make bench`; nothing is hard-coded.
The output is deterministic, so CI can check that it reproduces.
"""
import csv
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "results"
OUT = Path(sys.argv[1]) if len(sys.argv) > 1 else RES / "summary.md"
TX_CAP = 2**24


def load(name):
    """variant -> {param: row}"""
    d = defaultdict(dict)
    with open(RES / name) as f:
        for r in csv.DictReader(f):
            d[r["variant"]][int(r["param"])] = {k: int(v) for k, v in r.items() if k != "variant"}
    return d


def g(d, variant, param):
    return d[variant][param]["tx_gas"]


def n(x):
    return f"{x:,}"


def pct(x, base):
    return f"{100 * (x - base) / base:+.1f}%"


def fit(points):
    """Least-squares line through (x, y) points: (slope, intercept)."""
    k = len(points)
    sx = sum(x for x, _ in points)
    sy = sum(y for _, y in points)
    sxx = sum(x * x for x, _ in points)
    sxy = sum(x * y for x, y in points)
    slope = (k * sxy - sx * sy) / (k * sxx - sx * sx)
    return slope, (sy - slope * sx) / k


out = []
w = out.append
w("# Measured results")
w("")
w("Generated by `scripts/summarize.py` from `results/*.csv` (`make report`); do not edit by hand.")
w("All values are full transaction gas (`tx_gas`). Paper references are to Section 6.")
w("")

# ------------------------------------------------------------------ transfers
t = load("transfer_holds.csv")
base = g(t, "baseline", 0)
w("## Transfer cost (Figure 2a)")
w("")
w("| Design | 0 holds | 16 holds | vs. ERC-20 (0 holds) |")
w("|---|---:|---:|---:|")
names = [
    ("baseline", "ERC-20 baseline"),
    ("enforced_packed", "Packed slot (this work)"),
    ("blacklist_mapping", "Blacklist mapping (no holds)"),
    ("separate_aggregate", "Separate status + aggregate held"),
    ("naive_holds", "Separate status + hold array"),
]
for v, label in names:
    g0 = g(t, v, 0)
    g16 = g(t, v, 16) if 16 in t[v] else None
    w(f"| {label} | {n(g0)} | {n(g16) if g16 is not None else '—'} | "
      f"{'—' if v == 'baseline' else f'+{n(g0 - base)} ({pct(g0, base)})'} |")
packed = g(t, "enforced_packed", 0)
w("")
w(f"- Packed design minus separate status + aggregate: {n(g(t, 'separate_aggregate', 0) - packed)} gas per transfer.")
w(f"- Hold array: {n((g(t, 'naive_holds', 16) - g(t, 'naive_holds', 0)) // 16)} gas per active hold "
  f"(from 0 to 16 holds).")
w(f"- Packed design independent of holds: "
  f"{'yes' if len({g(t, 'enforced_packed', k) for k in t['enforced_packed']}) == 1 else 'NO'}.")
w("")

# ------------------------------------------------------------------ SMT transfers
s = load("smt_transfer.csv")
w("## Transfer with SMT non-membership proofs (Figure 2b)")
w("")
w("| Restricted addresses N | Tx gas | vs. packed | Calldata bytes |")
w("|---:|---:|---:|---:|")
for N, r in sorted(s["smt_proofs"].items()):
    w(f"| {n(N)} | {n(r['tx_gas'])} | {r['tx_gas'] / packed:.2f}× | {n(r['calldata_bytes'])} |")
w("")

# ------------------------------------------------------------------ list updates
b = load("batch_update.csv")
w("## Restriction-list update, 2-of-3 quorum (Table 5, Figure 2c)")
w("")
w("Marginal cost from a least-squares fit over K ∈ [500, 1000]; max K is where the fitted line reaches 2²⁴.")
w("")
w("| Design | K = 1 | Marginal per address | Max. K under 2²⁴ | Measured K above the cap |")
w("|---|---:|---:|---:|---|")
for v, label in [("mapping", "Separate mapping"), ("packed_unfunded", "Packed, zero-balance targets"),
                 ("packed_funded", "Packed, funded targets"), ("smt_root", "SMT root")]:
    pts = [(k, r["tx_gas"]) for k, r in b[v].items() if 500 <= k <= 1000]
    slope, icpt = fit(pts)
    over = sorted(k for k, r in b[v].items() if r["exceeds_eip7825"])
    if v == "smt_root":
        lo, hi = min(r["tx_gas"] for r in b[v].values()), max(r["tx_gas"] for r in b[v].values())
        w(f"| {label} | {n(g(b, v, 1))} | ≈0 ({n(lo)}–{n(hi)} for every K) | unbounded | none |")
    else:
        kmax = int((TX_CAP - icpt) // slope)
        extra = " (extrapolated)" if kmax > max(b[v]) else ""
        w(f"| {label} | {n(g(b, v, 1))} | {n(round(slope))} | ≈{n(kmax)}{extra} | "
          f"{', '.join(n(k) for k in over) or 'none'} |")
w("")

# ------------------------------------------------------------------ quorum
q = load("quorum.csv")
w("## Quorum size, freezing a zero-balance account (Table 6)")
w("")
w("| Authorization | Tx gas |")
w("|---|---:|")
single = g(q, "single_key", 1)
w(f"| Single key | {n(single)} |")
for m, r in sorted(q["quorum"].items()):
    w(f"| {m}-of-{m + 2} | {n(r['tx_gas'])} |")
steps = [g(q, "quorum", m + 1) - g(q, "quorum", m) for m in range(1, max(q["quorum"]))]
w("")
w(f"- Fixed quorum overhead (1-of-3 minus single key): {n(g(q, 'quorum', 1) - single)} gas.")
w(f"- Per additional signer: {', '.join(n(x) for x in steps)} (mean {n(round(sum(steps) / len(steps)))}).")
w(f"- 2-of-N minus single key: {n(g(q, 'quorum', 2) - single)} gas.")
w("")

# ------------------------------------------------------------------ lifecycle
L = load("lifecycle.csv")
w("## Enforcement lifecycle on a funded account, 2-of-3 quorum (Table 7)")
w("")
w("| Action | Tx gas |")
w("|---|---:|")
for v, label in [("freeze", "Freeze"), ("place_hold", "Hold (place)"), ("seize_full", "Seize (full hold)"),
                 ("burn_partial", "Burn (partial hold)"), ("release", "Release"), ("unfreeze", "Unfreeze")]:
    w(f"| {label} | {n(g(L, v, 0))} |")
w("")
w(f"- Hold then seize: {n(g(L, 'place_hold', 0) + g(L, 'seize_full', 0))} gas.")
zq, fl = q["quorum"][2], L["freeze"][0]
w(f"- Freezing a zero-balance account (2-of-4, Table 6) minus a funded one (2-of-3): "
  f"{n(zq['tx_gas'] - fl['tx_gas'])} gas, of which {n(zq['exec_gas'] - fl['exec_gas'])} execution gas "
  f"and {zq['intrinsic_gas'] - fl['intrinsic_gas']:+,} intrinsic (calldata) gas.")
w("  Mixing N = 4 and N = 3 is sound: verification cost depends on M only, and the execution difference is "
  "that of a zero-to-non-zero versus a non-zero-to-non-zero storage write (20,000 − 2,900 = 17,100).")
w("")

# ------------------------------------------------------------------ tiered
T = {v: r[max(r)] for v, r in load("tiered.csv").items()}
tg = {v: r["tx_gas"] for v, r in T.items()}
w("## Tiered authority (Table 8)")
w("")
w("Fast tier 2-of-5, slow tier 3-of-5 over two roles, guardians 2-of-3; single-threshold column with M = 2 "
  "(N = 4 from Table 6 for the zero-balance freeze, N = 3 from Table 7 otherwise; the cost depends on M only).")
w("")
w("| Action | TieredAuthority | ComplianceAuthority | Difference |")
w("|---|---:|---:|---:|")
rows = [
    ("Freeze, zero-balance account (fast)", tg["fast_freeze_zero_balance"], g(q, "quorum", 2)),
    ("Freeze, funded account (fast)", tg["fast_freeze_funded"], g(L, "freeze", 0)),
    ("Place hold (fast)", tg["fast_place_hold"], g(L, "place_hold", 0)),
]
for label, a, c in rows:
    w(f"| {label} | {n(a)} | {n(c)} | +{n(a - c)} |")
for label, qv, ev, c in [("Seize full hold (slow: queue + execute)", "slow_queue_seize", "slow_execute_seize",
                          g(L, "seize_full", 0)),
                         ("Unfreeze (slow: queue + execute)", "slow_queue_unfreeze", "slow_execute_unfreeze",
                          g(L, "unfreeze", 0))]:
    tot = tg[qv] + tg[ev]
    w(f"| {label} | {n(tg[qv])} + {n(tg[ev])} = {n(tot)} | {n(c)} | {tot / c:.2f}× |")
w(f"| Guardian cancellation | {n(tg['guardian_cancel'])} | — | — |")
extra = [a - c for _, a, c in rows]
w("")
w(f"- Fast-tier extra cost: {n(min(extra))}–{n(max(extra))} gas.")
w(f"- Zero-balance minus funded fast-tier freeze, one signer set: "
  f"{n(tg['fast_freeze_zero_balance'] - tg['fast_freeze_funded'])} gas, of which "
  f"{n(T['fast_freeze_zero_balance']['exec_gas'] - T['fast_freeze_funded']['exec_gas'])} execution gas.")
w(f"- Hold then seize through the tiers: "
  f"{n(tg['fast_place_hold'] + tg['slow_queue_seize'] + tg['slow_execute_seize'])} gas.")
w("")

# ------------------------------------------------------------------ bridge
B = {v: r[max(r)]["tx_gas"] for v, r in load("bridge.csv").items()}
w("## Bridging (Section 6.4, Bridging)")
w("")
w("| Action | Tx gas |")
w("|---|---:|")
for v, label in [("bridge_out_burn", "Bridge-out through the adapter (burn)"),
                 ("bridge_in_mint", "Bridge-in through the adapter (mint)"),
                 ("bridged_token_transfer", "Plain transfer on the bridged token"),
                 ("fast_bridge_shutdown", "Fast-tier bridge shutdown, 2-of-5")]:
    w(f"| {label} | {n(B[v])} |")
w("")
w(f"- Transfer on the bridged token equals the packed design: {'yes' if B['bridged_token_transfer'] == packed else 'NO'}.")
w("")
w("The ingestion demo's batch costs (Section 6.4, List ingestion) are printed by `make ingest`, not stored in a CSV.")

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("\n".join(out) + "\n")
print("written to", OUT)
